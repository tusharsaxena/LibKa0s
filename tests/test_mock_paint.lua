  local s = M.__paint(f)
  assertEqual(s.kind, "Frame"); assertEqual(s.alpha, 0.5); assertTrue(s.backdrop == bd)
  f:SetBackdrop(nil)
  assertNil(f:GetBackdrop())
end)

