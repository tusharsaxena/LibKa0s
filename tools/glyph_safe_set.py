#!/usr/bin/env python3
"""Regenerate the glyph guard's safe set in testkit/glyphs.lua from the shipped faces.

The kit's display-glyph guard (testkit/glyphs.lua, kit revision 45; LK-12 of Ka0sAddonsCommonTasks
docs/2026-10-30-SKIN_FONTS_AND_FEEDBACK, ruling D-19) passes a display string only when every
character in it is one EVERY face a shipped skin draws with can draw: printable ASCII, and the
non-ASCII code points this script finds in the cmap of every .ttf in LibKa0s/media/fonts. That
folder holds exactly the faces the skins name (the body, title and HUD faces, and JetBrains Mono,
the mono role), because LK-02 removed every face no skin uses.

Real Friz Quadrata, WoW Default's face and the client's own, is not in the folder and is not
measured (D-05: on the owner's client Fonts/FRIZQT__.TTF is Prototype; IS-07 asks for a real
measurement). The set is therefore exact for the shipped faces and assumed for Friz.

Usage, from the repo root (needs fontTools):

    python3 tools/glyph_safe_set.py           # rewrite the generated block in testkit/glyphs.lua
    python3 tools/glyph_safe_set.py --check   # exit 1 when the block is stale, write nothing

Then re-vendor the kit (cp -r testkit/. tests/_kit/). tests/test_glyph_guard.lua is red while the
block's face list (name and byte size) disagrees with the folder, so a face added, removed or
replaced without a rerun is caught by the suite, not by a player.
"""

import os
import sys

from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "LibKa0s", "media", "fonts")
TARGET = os.path.join(ROOT, "testkit", "glyphs.lua")
BEGIN = "-- BEGIN GENERATED by tools/glyph_safe_set.py: do not edit by hand"
END = "-- END GENERATED"


def faces():
    out = []
    for name in sorted(os.listdir(FONTS)):
        if name.lower().endswith((".ttf", ".otf")):
            path = os.path.join(FONTS, name)
            out.append((name, os.path.getsize(path), set(TTFont(path).getBestCmap().keys())))
    if not out:
        sys.exit("no faces in " + FONTS)
    return out


def ranges(points):
    out = []
    for cp in sorted(points):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def block(found):
    common = set.intersection(*(cmap for _, _, cmap in found))
    missing = [n for n, _, cmap in found if not all(c in cmap for c in range(0x20, 0x7F))]
    if missing:
        sys.exit("these faces lack printable ASCII, which the guard assumes: " + ", ".join(missing))
    lines = [BEGIN, "local FACES = {"]
    for name, size, _ in found:
        lines.append('  { file = "%s", bytes = %d },' % (name, size))
    lines.append("}")
    lines.append("local RANGES = {")
    row = []
    for lo, hi in ranges(c for c in common if c >= 0x80):
        row.append("{ 0x%04X, 0x%04X }," % (lo, hi))
        if len(row) == 5:
            lines.append("  " + " ".join(row))
            row = []
    if row:
        lines.append("  " + " ".join(row))
    lines.append("}")
    lines.append(END)
    return lines


def main():
    check = "--check" in sys.argv[1:]
    with open(TARGET, "rb") as f:
        text = f.read().decode("utf-8")
    eol = "\r\n" if "\r\n" in text else "\n"
    start, stop = text.find(BEGIN), text.find(END)
    if start < 0 or stop < start:
        sys.exit("no generated block in " + TARGET)
    stop += len(END)
    new = text[:start] + eol.join(block(faces())) + text[stop:]
    if new == text:
        print("glyphs.lua is current")
        return 0
    if check:
        print("glyphs.lua is stale: run python3 tools/glyph_safe_set.py")
        return 1
    with open(TARGET, "wb") as f:
        f.write(new.encode("utf-8"))
    print("wrote " + os.path.relpath(TARGET, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
