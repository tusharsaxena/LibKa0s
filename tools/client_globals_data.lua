-- tools/client_globals_data.lua -- writes testkit/client_globals_<branch>.lua (kit revision 53).
--
--   lua tools/client_globals_data.lua <branch> <sha> <date> <dir holding GlobalAPI.lua and FrameXML.lua>
--
-- Source: Ketho/BlizzardInterfaceResources, branches `live` and `forever`, read with
--   gh api -H "Accept: application/vnd.github.raw" \
--     "repos/Ketho/BlizzardInterfaceResources/contents/Resources/<File>.lua?ref=<branch>"
-- for GlobalAPI.lua and FrameXML.lua. It keeps only what testkit/client_globals.lua asks about: the
-- global function names (the C API, the Lua API, the FrameXML functions) and the members of the C_*
-- namespaces, as `C_Name.Member`. Sorted, one space between names, wrapped at 110 columns.
local branch, sha, date, dir = ...
assert(branch and sha and date and dir, "usage: client_globals_data.lua <branch> <sha> <date> <dir>")

local function readNames(path, first)
  local f = assert(io.open(path, "rb")); local s = f:read("*a"); f:close()
  local out, n = {}, 0
  for block in s:gmatch("local %w+ = (%b{})") do
    n = n + 1
    if not first or n <= first then
      for name in block:gmatch('"([%w_%.]+)"') do out[#out + 1] = name end
    end
  end
  return out
end

local set = {}
for _, spec in ipairs({ { "GlobalAPI.lua" }, { "FrameXML.lua", 1 } }) do
  for _, name in ipairs(readNames(dir .. "/" .. spec[1], spec[2])) do
    if not name:find(".", 1, true) or name:find("^C_[%w_]+%.[%w_]+$") then set[name] = true end
  end
end
local list = {}
for name in pairs(set) do list[#list + 1] = name end
table.sort(list)

local function wrap(names)
  local lines, line = {}, ""
  for _, name in ipairs(names) do
    if #line + #name + 1 > 110 then lines[#lines + 1] = line; line = "" end
    line = (line == "" and "" or line .. " ") .. name
  end
  lines[#lines + 1] = line
  return table.concat(lines, "\n")
end

local head = ("return {\n  repo = \"Ketho/BlizzardInterfaceResources\", branch = %q,\n  sha = %q,\n  date = %q,\n")
  :format(branch, sha, date)
  .. "  files = { \"Resources/GlobalAPI.lua\", \"Resources/FrameXML.lua\" },\n"
local body
if branch == "live" then
  body = "  names = [[\n" .. wrap(list) .. "\n]],\n}\n"
else
  -- Any other branch is stored as its difference from `live` (run `live` first): about half the bytes.
  local base = {}
  for name in assert(dofile("testkit/client_globals_live.lua")).names:gmatch("%S+") do base[name] = true end
  local added, removed = {}, {}
  for _, name in ipairs(list) do if not base[name] then added[#added + 1] = name end end
  for name in pairs(base) do if not set[name] then removed[#removed + 1] = name end end
  table.sort(removed)
  body = "  base = \"live\",\n  added = [[\n" .. wrap(added) .. "\n]],\n  removed = [[\n" .. wrap(removed) .. "\n]],\n}\n"
end
local out = assert(io.open("testkit/client_globals_" .. branch .. ".lua", "wb"))
out:write(("-- Generated by tools/client_globals_data.lua; do not edit. %d names.\n"):format(#list), head, body)
out:close()
print(branch, #list)
