class Fixture:
    """A scratch repo shaped like LibKa0s (testkit/, LibKa0s/, tools/), and a bundle."""

    def __init__(self, kit_sha: str = SHA_OLD):
        self.dir = Path(tempfile.mkdtemp(prefix="test-libseeds-"))
        (self.dir / "testkit").mkdir()
        (self.dir / "tests" / "_kit").mkdir(parents=True)
        (self.dir / "LibKa0s").mkdir()
        (self.dir / "tools").mkdir()
        (self.dir / "testkit" / "client_globals_live.lua").write_text(LIVE_KIT.replace(SHA_OLD, kit_sha))
        (self.dir / "testkit" / "client_globals_forever.lua").write_text(FOREVER_KIT.replace(SHA_OLD, kit_sha))
        (self.dir / "LibKa0s" / "Fake.lua").write_text(PAYLOAD)
        shutil.copy(L.REPO / L.GENERATOR, self.dir / L.GENERATOR)
        self.tools = self.dir / "tools" / "seeds"
        self.tools.mkdir()

    def bundle(self, flavor: str, sha: str = SHA_NEW) -> Path:
        bundle = self.dir / "docs" / "seed-research" / ("2026-11-25-" + flavor)
        (bundle / "raw").mkdir(parents=True)
        for name, text in (("GlobalAPI.lua", GLOBAL_API), ("FrameXML.lua", FRAME_XML), ("LuaEnum.lua", LUA_ENUM)):
            (bundle / "raw" / (name + ".gz")).write_bytes(gzip.compress(text.encode(), mtime=0))
        src = {"flavor": flavor, "branch": L.FLAVORS[flavor]["branch"], "sha": sha, "shaDate": "2026-11-14",
               "date": "2026-11-25", "files": {}}
        (bundle / "sources.json").write_text(json.dumps(src))
        return bundle

    def close(self):
        shutil.rmtree(self.dir, ignore_errors=True)


class ReaderTests(unittest.TestCase):
    def test_upstream_names_follow_the_generator(self):
        names = L.upstream_names(GLOBAL_API, FRAME_XML)
        self.assertEqual(names, {"FakeAlpha", "FakeBeta", "C_Fake.Member", "C_Fake.Other", "pairs", "type",
                                 "FakeFrame_OnLoad"})

    def test_parse_enums(self):
        enums = L.parse_enums(LUA_ENUM)
        self.assertEqual(enums, {"FakeRule": {"First", "Second"}, "FakeBag": {"Backpack"}})
        self.assertEqual(L.parse_enums("nothing here"), {})

    def test_kit_sets(self):
        fx = Fixture()
        try:
            kit, live = L.kit_set("retail", fx.dir)
            self.assertEqual(kit["sha"], SHA_OLD)
            self.assertEqual(live, {"C_Fake.Member", "FakeAlpha", "pairs", "type"})
            kit, forever = L.kit_set("forever", fx.dir)
            self.assertEqual(kit["date"], "2026-01-02")
            self.assertEqual(forever, {"C_Fake.Member", "FakeForeverOnly", "pairs", "type"})
        finally:
            fx.close()

    def test_strip_lua_blanks_comments_and_strings_and_keeps_lines(self):
        src = 'a("x(y)") -- c(d)\n--[[ e(f)\n]] g[[h(i)]] \'j\\\'k(\'\n'
        out = L.strip_lua(src)
        self.assertEqual(len(out), len(src))
        self.assertEqual(out.count("\n"), src.count("\n"))
        self.assertNotIn("c(d)", out)
        self.assertNotIn("e(f)", out)
        self.assertNotIn("h(i)", out)
        self.assertNotIn("k(", out)
        self.assertIn("a(", out)
        self.assertIn("g", out)


class ScanTests(unittest.TestCase):
    def setUp(self):
        self.fx = Fixture()

    def tearDown(self):
        self.fx.close()

    def test_scan_reads_enums_aliases_namespaces_and_bare_calls(self):
        known = {"FakeAlpha", "FakeGone", "pairs", "print", "own", "C_Fake.Member"}  # not FakeForeverOnly
        found = L.scan_payload(self.fx.dir, known)
        self.assertEqual(sorted(found["enum"]), ["FakeBag.Backpack", "FakeRule", "FakeRule.First", "FakeRule.Third",
                                                 "NoSuchEnum"])
        self.assertEqual(sorted(found["capi"]), ["C_Fake.Member", "C_Fake.Missing"])
        # `own` is the file's local function; a name only in a comment or string is no call.
        self.assertEqual(sorted(found["global"]), ["FakeAlpha", "FakeGone", "pairs", "print"])
        self.assertEqual(found["global"]["FakeAlpha"], ["LibKa0s/Fake.lua:10"])

    def test_scan_flags_a_cached_global_at_its_capture(self):
        (self.fx.dir / "LibKa0s" / "Cache.lua").write_text(
            "local FakeGone = FakeGone\n"
            "local FakeAlpha, n = _G.FakeAlpha, 3\n"
            "local Unknown = Unknown\n"
            "local Other = FakeAlpha\n"
            "return function() return FakeGone(), Unknown(), Other() end\n")
        known = {"FakeAlpha", "FakeGone", "pairs", "print", "own", "C_Fake.Member"}
        found = L.scan_payload(self.fx.dir, known)
        # The capture is the read; the later call goes through the upvalue. A name no source knows,
        # and a local copied from another local's name, are not client reads.
        self.assertEqual(found["global"]["FakeGone"], ["LibKa0s/Cache.lua:1", "LibKa0s/Fake.lua:11"])
        self.assertEqual(found["global"]["FakeAlpha"], ["LibKa0s/Cache.lua:2", "LibKa0s/Fake.lua:10"])
        self.assertNotIn("Unknown", found["global"])

    def test_missing_on(self):
        enums = L.parse_enums(LUA_ENUM)
        self.assertFalse(L.missing_on("enum", "FakeRule", set(), enums))
        self.assertFalse(L.missing_on("enum", "FakeRule.First", set(), enums))
        self.assertTrue(L.missing_on("enum", "FakeRule.Third", set(), enums))
        self.assertTrue(L.missing_on("enum", "NoSuchEnum", set(), enums))
        self.assertTrue(L.missing_on("capi", "C_Fake.Missing", {"C_Fake.Member"}, enums))
        self.assertFalse(L.missing_on("global", "FakeAlpha", {"FakeAlpha"}, enums))


class DeriveTests(unittest.TestCase):
    def setUp(self):
        self.fx = Fixture()

    def tearDown(self):
        self.fx.close()

    def test_derive_proposes_a_regeneration_and_flags_absent_assumptions(self):
        # The coverage gate wants a real-sized source; lower it for the fixture.
        doc = self._derive("forever")
        self.assertEqual([c["key"] for c in doc["candidates"]], ["regen:forever"])
        self.assertEqual(doc["diff"]["added"], ["C_Fake.Other", "FakeAlpha", "FakeBeta", "FakeFrame_OnLoad"])
        self.assertEqual(doc["diff"]["removed"], ["FakeForeverOnly"])
        self.assertEqual(doc["reach"]["unreached"], ["FakeForeverOnly"])
        keys = [f["key"] for f in doc["flags"]]
        self.assertIn("shipped:enum:FakeRule.Third", keys)
        self.assertIn("shipped:enum:NoSuchEnum", keys)
        self.assertIn("shipped:capi:C_Fake.Missing", keys)
        # Known to the kit but gone upstream: an assumption that fails. Known nowhere: the file's own.
        self.assertIn("shipped:global:FakeForeverOnly", keys)
        self.assertNotIn("shipped:global:FakeGone", keys)
        self.assertNotIn("shipped:global:FakeAlpha", keys)
        self.assertEqual(doc["build"], SHA_NEW)
        self.assertEqual(doc["buildDate"], "2026-11-14")

    def test_no_regeneration_when_the_kit_is_at_the_sha(self):
        doc = self._derive("retail", sha=SHA_OLD)
        self.assertEqual(doc["candidates"], [])

    def test_the_coverage_gate_refuses_a_thin_source(self):
        bundle = self.fx.bundle("retail")
        with self.assertRaises(SystemExit):
            L.derive_doc(bundle, self.fx.dir)

    def test_derive_needs_raw(self):
        bundle = self.fx.bundle("retail")
        (bundle / "raw" / "LuaEnum.lua.gz").unlink()
        with self.assertRaises(SystemExit):
            L.derive_doc(bundle, self.fx.dir)

    def _derive(self, flavor, sha=SHA_NEW):
        bundle = self.fx.bundle(flavor, sha)
        filler = "".join('\t"FakeFiller%04d",\n' % i for i in range(1000)) + '\t"C_Timer.After",\n'
        text = GLOBAL_API.replace('\t"pairs",\n', '\t"pairs",\n' + filler)
        (bundle / "raw" / "GlobalAPI.lua.gz").write_bytes(gzip.compress(text.encode(), mtime=0))
        doc = L.derive_doc(bundle, self.fx.dir)
        filler_names = {"FakeFiller%04d" % i for i in range(1000)} | {"C_Timer.After"}
        doc["diff"]["added"] = [n for n in doc["diff"]["added"] if n not in filler_names]
        return doc


class RulingTests(unittest.TestCase):
    DOC = {"flavor": "forever", "candidates": [{"key": "regen:forever", "name": "x", "notes": []}],
           "flags": [{"key": "shipped:capi:C_Fake.Missing", "shipped": "C_Fake.Missing", "build": "absent", "notes": ["f:1"]}]}

    def test_set_ruling_validates(self):
        rulings = {}
        L.set_ruling(rulings, "regen:forever", "accept", "the branch moved")
        L.set_ruling(rulings, "shipped:capi:C_Fake.Missing", "keep", "guarded at f:1")
        self.assertEqual(rulings["regen:forever"]["ruling"], "accept")
        for key, ruling, reason in (("regen:forever", "keep", "x"), ("shipped:capi:X", "accept", "x"),
                                    ("shipped:bogus:X", "keep", "x"), ("nope", "accept", "x"),
                                    ("regen:forever", "accept", ""), ("regen:forever", "accept", "a\nb")):
            with self.assertRaises(SystemExit):
                L.set_ruling({}, key, ruling, reason)

    def test_unruled_and_apply_refusals(self):
        self.assertEqual(L.unruled(self.DOC, {}), ["regen:forever", "shipped:capi:C_Fake.Missing"])
        with self.assertRaises(SystemExit):
            L.plan_apply(self.DOC, {})
        fix = {"regen:forever": {"ruling": "accept", "reason": "r"},
               "shipped:capi:C_Fake.Missing": {"ruling": "fix", "reason": "r"}}
        with self.assertRaises(SystemExit):
            L.plan_apply(self.DOC, fix)
        fix["shipped:capi:C_Fake.Missing"]["ruling"] = "keep"
        self.assertTrue(L.plan_apply(self.DOC, fix))
        fix["regen:forever"]["ruling"] = "reject"
        self.assertFalse(L.plan_apply(self.DOC, fix))

    def test_read_tsv(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "r.tsv"
            path.write_text("# comment\nregen:forever\taccept\tmoved\n\n")
            self.assertEqual(L.read_tsv(path), [("regen:forever", "accept", "moved")])
            path.write_text("regen:forever\taccept\n")
            with self.assertRaises(SystemExit):
                L.read_tsv(path)

    def test_reports_render(self):
        doc = dict(self.DOC, date="2026-11-25", build=SHA_NEW, branch="forever", buildDate="2026-11-14",
                   kit={"path": "testkit/client_globals_forever.lua", "sha": SHA_OLD, "date": "2026-01-02", "names": 4},
                   upstream={"names": 7, "enums": 2}, diff={"added": ["A"], "removed": []},
                   reach={"kitNames": 4, "unreached": []},
                   assumptions={k: {"count": 1, "missing": 0} for k in L.FLAG_KINDS})
        text = L.format_rulings(doc, {}, "2026-11-25")
        self.assertIn("## Unruled -- 2", text)
        self.assertIn("**unruled**", text)
        diff = L.format_diff(doc)
        self.assertIn("## (a) Kit globals", diff)
        self.assertIn("## (c) Reach", diff)
        self.assertIn("Every name reaches.", diff)


class StatusTests(unittest.TestCase):
    def test_status_line(self):
        self.assertTrue(L.status_line(SHA_NEW, SHA_OLD, []).startswith("NEW " + SHA_NEW))
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp) / "2026-11-25-forever"
            bundle.mkdir()
            (bundle / "candidates.json").write_text(json.dumps({"build": SHA_NEW}))
            self.assertTrue(L.status_line(SHA_NEW, SHA_OLD, [bundle]).startswith("CURRENT " + SHA_NEW))
            self.assertTrue(L.status_line("c" * 40, SHA_OLD, [bundle]).startswith("NEW " + "c" * 40))

    def test_flavor_of(self):
        self.assertEqual(L.flavor_of(Path("x/2026-11-25-forever"), None), "forever")
        self.assertEqual(L.flavor_of(Path("x/whatever"), "retail"), "retail")
        with self.assertRaises(SystemExit):
            L.flavor_of(Path("x/whatever"), None)


@unittest.skipIf(shutil.which("lua") is None, "the generator needs lua")
class RegenerateTests(unittest.TestCase):
    def test_regenerate_writes_crlf_into_both_copies_and_is_idempotent(self):
        fx = Fixture()
        try:
            bundle = fx.bundle("forever")
            doc = {"flavor": "forever", "branch": "forever", "build": SHA_NEW, "buildDate": "2026-11-14"}
            changed = L.regenerate(doc, bundle, fx.dir)
            self.assertEqual(changed, ["testkit/client_globals_forever.lua", "tests/_kit/client_globals_forever.lua"])
            data = (fx.dir / "testkit" / "client_globals_forever.lua").read_bytes()
            self.assertEqual(data, (fx.dir / "tests" / "_kit" / "client_globals_forever.lua").read_bytes())
            self.assertEqual(data.count(b"\r\n"), data.count(b"\n"))
            text = data.decode()
            self.assertIn('sha = "%s"' % SHA_NEW, text)
            self.assertIn('date = "2026-11-14"', text)
            kit, names = L.kit_set("forever", fx.dir)
            self.assertEqual(names, L.upstream_names(GLOBAL_API, FRAME_XML))
            self.assertEqual(L.regenerate(doc, bundle, fx.dir), [])
        finally:
            fx.close()


