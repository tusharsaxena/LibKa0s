def _date(value: str) -> str:
    if not DATE_RE.match(value):
        raise argparse.ArgumentTypeError("a date is YYYY-MM-DD; got %r" % value)
    return value


def _sha(value: str) -> str:
    if not SHA_RE.match(value):
        raise argparse.ArgumentTypeError("a build is a full 40-character commit sha; got %r" % value)
    return value


def flavor_of(bundle: Path, given: str | None) -> str:
    if given:
        return given
    for flavor in FLAVORS:
        if bundle.name.endswith("-" + flavor):
            return flavor
    raise SystemExit("name the flavor: %s does not end in -retail or -forever." % bundle)


def cmd_status(args) -> int:
    for flavor in ([args.flavor] if args.flavor else list(FLAVORS)):
        kit = read_kit(args.repo / FLAVORS[flavor]["kit"])
        line = status_line(branch_head(FLAVORS[flavor]["branch"]), kit["sha"], bundles(flavor, args.root))
        print(line if args.flavor else "%s: %s" % (flavor, line))
    return 0


def cmd_freeze(args) -> int:
    flavor = flavor_of(args.bundle, args.flavor)
    sha_date = args.sha_date or commit_date(args.sha)
    files = {}
    for name in FILES:
        log("Fetching %s at %s" % (name, args.sha[:12]))
        data = fetch_file(args.sha, name, args.cache_dir).read_bytes()
        member = args.bundle / "raw" / (name + ".gz")
        member.parent.mkdir(parents=True, exist_ok=True)
        member.write_bytes(gzip.compress(data, mtime=0))
        files[name] = {"bytes": len(data), "sha256": sha256_bytes(data)}
    src = {"flavor": flavor, "branch": FLAVORS[flavor]["branch"], "sha": args.sha, "shaDate": sha_date, "date": args.date,
           "files": files}
    write_json(args.bundle / "sources.json", src)
    write_repo_text(args.bundle / "SOURCES.md", format_sources(src))
    log("Froze %d files into %s" % (len(FILES), args.bundle))
    return 0


def cmd_derive(args) -> int:
    doc = derive_doc(args.bundle, args.repo)
    write_json(args.bundle / "candidates.json", doc)
    missing = unruled(doc, load_rulings(rulings_path(doc["flavor"], args.tool_dir)))
    log("%d candidates, %d flags, %d unruled; %d added, %d removed upstream"
        % (len(doc["candidates"]), len(doc["flags"]), len(missing), len(doc["diff"]["added"]), len(doc["diff"]["removed"])))
    return 0


def cmd_rule(args) -> int:
    doc = load_doc(args.bundle)
    todo = [(k, args.ruling, args.reason) for k in (args.key or ())]
    if args.tsv:
        todo += read_tsv(args.tsv)
    if not todo:
        raise SystemExit("rule needs --key (with --ruling and --reason) or --tsv.")
    known = set(all_keys(doc))
    path = rulings_path(doc["flavor"], args.tool_dir)
    rulings = load_rulings(path)
    for key, ruling, reason in todo:
        if key not in known:
            raise SystemExit("%s is not a candidate or flag in %s/candidates.json." % (key, args.bundle))
        set_ruling(rulings, key, ruling, reason)
    save_rulings(path, rulings)
    log("Recorded %d ruling(s) in %s" % (len(todo), path))
    return 0


def cmd_check(args) -> int:
    doc = load_doc(args.bundle)
    missing = unruled(doc, load_rulings(rulings_path(doc["flavor"], args.tool_dir)))
    if not missing:
        print("OK: every candidate and flag in %s is ruled." % args.bundle.name)
        return 0
    rows = {r["key"]: r for r in doc["candidates"] + doc["flags"]}
    print("%d unruled:" % len(missing))
    for key in missing:
        row = rows[key]
        print("  %s  %s" % (key, row.get("name") or "; ".join(row["notes"])))
    return 1


def cmd_report(args) -> int:
    doc = load_doc(args.bundle)
    rulings = load_rulings(rulings_path(doc["flavor"], args.tool_dir))
    write_repo_text(args.bundle / "RULINGS.md", format_rulings(doc, rulings, args.date))
    write_repo_text(args.bundle / "DIFF.md", format_diff(doc))
    log("Wrote %s and %s" % (args.bundle / "RULINGS.md", args.bundle / "DIFF.md"))
    return 0


def cmd_apply(args) -> int:
    doc = load_doc(args.bundle)
    if not plan_apply(doc, load_rulings(rulings_path(doc["flavor"], args.tool_dir))):
        log("Nothing to apply for %s (%s)." % (doc["flavor"], args.date))
        return 0
    changed = regenerate(doc, args.bundle, args.repo)
    for rel in changed:
        log("  wrote " + rel)
    if changed:
        log("%d file(s) changed (%s). A changed name set is a kit revision: bump Kit.VERSION." % (len(changed), args.date))
    else:
        log("No change (%s): the kit file already matches the bundle." % args.date)
    return 0


def parse_args(argv):
    parser = argparse.ArgumentParser(description="Re-validate LibKa0s's client data against Ketho/BlizzardInterfaceResources.",
                                     epilog="The procedure is docs/validate-seeds.md.")
    parser.add_argument("--repo", type=Path, default=REPO, help=argparse.SUPPRESS)
    parser.add_argument("--tool-dir", type=Path, default=HERE, help=argparse.SUPPRESS)
    parser.add_argument("--cache-dir", type=Path, default=CACHE, help="the per-sha download cache")
    sub = parser.add_subparsers(dest="command", required=True)
    status = sub.add_parser("status", help="has the branch moved past the kit file and the newest bundle?")
    status.add_argument("--flavor", choices=sorted(FLAVORS))
    status.add_argument("--root", type=Path, default=RESEARCH, help=argparse.SUPPRESS)
    freeze = sub.add_parser("freeze", help="fetch the three files at the sha into the bundle's raw/")
    freeze.add_argument("--flavor", choices=sorted(FLAVORS))
    freeze.add_argument("--sha", type=_sha, required=True)
    freeze.add_argument("--date", type=_date, required=True)
    freeze.add_argument("--bundle", type=Path, required=True)
    freeze.add_argument("--sha-date", type=_date, help="the commit's date, when the API is out of reach")
    derive = sub.add_parser("derive", help="candidates and flags into the bundle's candidates.json, from raw/ alone")
    derive.add_argument("--bundle", type=Path, required=True)
    rule = sub.add_parser("rule", help="record rulings (the only writer of the rulings file)")
    rule.add_argument("--bundle", type=Path, required=True)
    rule.add_argument("--tsv", type=Path, help="key<TAB>ruling<TAB>reason lines")
    rule.add_argument("--key", action="append")
    rule.add_argument("--ruling")
    rule.add_argument("--reason")
    for name, text in (("check", "exit 1 while anything is unruled"), ("report", "write the bundle's RULINGS.md and DIFF.md"),
                       ("apply", "regenerate the kit file when its regen: candidate is accepted")):
        cmd = sub.add_parser(name, help=text)
        cmd.add_argument("--bundle", type=Path, required=True)
        if name != "check":
            cmd.add_argument("--date", type=_date, required=True)
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    return {"status": cmd_status, "freeze": cmd_freeze, "derive": cmd_derive, "rule": cmd_rule, "check": cmd_check,
            "report": cmd_report, "apply": cmd_apply}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
