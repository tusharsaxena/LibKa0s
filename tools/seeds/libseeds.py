def _cell(text) -> str:
    return str(text or "").replace("|", "\\|")


def format_sources(src: dict) -> str:
    lines = ["# Sources -- LibKa0s seed validation, %s (%s, branch `%s`)" % (src["date"], src["flavor"], src["branch"]), "",
             "Generated by `tools/seeds/libseeds.py freeze`. Frozen: this directory is never edited after the run, "
             "apart from the hand-written `ANALYSIS.md`.", "",
             "| Field | Value |", "| --- | --- |",
             "| Source | <%s>, branch `%s` |" % (GIT_URL, src["branch"]),
             "| Build (commit) | `%s` |" % src["sha"],
             "| Commit date | %s |" % src["shaDate"],
             "| Date | %s (the run's argument) |" % src["date"],
             "| User-Agent | `%s` |" % USER_AGENT, "",
             "## Files", "", "| File | Bytes | sha256 | URL |", "| --- | --- | --- | --- |"]
    for name in FILES:
        f = src["files"][name]
        lines.append("| `Resources/%s` | %d | `%s` | <%s> |" % (name, f["bytes"], f["sha256"], RAW_URL.format(sha=src["sha"], file=name)))
    lines += ["", "The files are in `raw/`, gzipped. The source repository declares no license; the files list the "
              "client's own API names and enum values, the facts the kit's name sets already carry. "
              "`libseeds.py derive` reads only `raw/`, so it re-derives this bundle offline.", ""]
    return "\n".join(lines)


def format_rulings(doc: dict, rulings: dict, date: str) -> str:
    tally: dict[str, int] = {}
    for key in all_keys(doc):
        r = rulings.get(key, {}).get("ruling", "unruled")
        tally[r] = tally.get(r, 0) + 1
    lines = ["# Rulings -- LibKa0s seed validation, %s (%s, build %s)" % (doc["date"], doc["flavor"], doc["build"]), "",
             "Generated by `tools/seeds/libseeds.py report` on %s from this bundle's `candidates.json` and "
             "`tools/seeds/%s_rulings.json`. Do not edit by hand." % (date, doc["flavor"]), "",
             "%d candidates, %d flags: %s." % (len(doc["candidates"]), len(doc["flags"]),
                                               ", ".join("%d %s" % (n, r) for r, n in sorted(tally.items())) or "none"), ""]
    missing = unruled(doc, rulings)
    if missing:
        lines += ["## Unruled -- %d" % len(missing), ""] + ["- `%s`" % k for k in missing] + [""]
    lines += ["## Candidates -- %d" % len(doc["candidates"]), ""]
    if doc["candidates"]:
        lines += ["| Key | What | Evidence | Ruling | Reason |", "| --- | --- | --- | --- | --- |"]
        for c in doc["candidates"]:
            r = rulings.get(c["key"], {})
            lines.append("| `%s` | %s | %s | %s | %s |" % (c["key"], _cell(c["name"]), _cell("; ".join(c["notes"])),
                                                     r.get("ruling", "**unruled**"), _cell(r.get("reason"))))
    else:
        lines.append("None.")
    lines += ["", "## Assumption flags -- %d" % len(doc["flags"]), ""]
    if doc["flags"]:
        lines += ["| Key | Upstream | Sites | Ruling | Reason |", "| --- | --- | --- | --- | --- |"]
        for f in doc["flags"]:
            r = rulings.get(f["key"], {})
            lines.append("| `%s` | %s | %s | %s | %s |" % (f["key"], _cell(f["build"]), _cell("; ".join(f["notes"])),
                                                     r.get("ruling", "**unruled**"), _cell(r.get("reason"))))
    else:
        lines.append("None.")
    lines.append("")
    return "\n".join(lines)


def _names_block(names: list[str]) -> list[str]:
    if not names:
        return ["None."]
    return ["```text"] + [" ".join(names[i:i + 6]) for i in range(0, len(names), 6)] + ["```"]


def format_diff(doc: dict) -> str:
    a = doc["assumptions"]
    lines = ["# Diff -- LibKa0s seed validation, %s (%s, build %s)" % (doc["date"], doc["flavor"], doc["build"]), "",
             "Generated by `tools/seeds/libseeds.py report`. Do not edit by hand.", "",
             "## (a) Kit globals", "",
             "`%s` records `%s` (%s), %d names. Branch `%s` at `%s` (%s) has %d names: %d added, %d removed."
             % (doc["kit"]["path"], doc["kit"]["sha"], doc["kit"]["date"], doc["kit"]["names"], doc["branch"], doc["build"],
                doc["buildDate"], doc["upstream"]["names"], len(doc["diff"]["added"]), len(doc["diff"]["removed"])), "",
             "### Added upstream -- %d" % len(doc["diff"]["added"]), ""]
    lines += _names_block(doc["diff"]["added"])
    lines += ["", "### Removed upstream -- %d" % len(doc["diff"]["removed"]), ""]
    lines += _names_block(doc["diff"]["removed"])
    lines += ["", "## (b) Payload assumptions", "",
              "| Kind | Read by the payload | Absent on `%s` |" % doc["branch"], "| --- | --- | --- |"]
    lines += ["| `%s` | %d | %d |" % (k, a[k]["count"], a[k]["missing"]) for k in FLAG_KINDS]
    lines += ["", "Every absent one is a flag in `RULINGS.md`.", "",
              "## (c) Reach", "",
              "%d of the kit file's %d names reach the branch head." % (doc["reach"]["kitNames"] - len(doc["reach"]["unreached"]),
                                                                       doc["reach"]["kitNames"]),
              "The unreached ones are (a)'s removed list." if doc["reach"]["unreached"] else "Every name reaches.", ""]
    return "\n".join(lines)


