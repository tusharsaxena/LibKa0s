def strip_lua(src: str) -> str:
    """`src` with every comment and string blanked to spaces (newlines kept, so lines still count)."""
    out, i, n = [], 0, len(src)
    blank = lambda s: re.sub(r"[^\n]", " ", s)  # noqa: E731
    while i < n:
        ch = src[i]
        if src.startswith("--", i):
            long = re.match(r"--\[(=*)\[", src[i:i + 64])
            if long:
                close = src.find("]" + long.group(1) + "]", i)
                stop = n if close < 0 else close + len(long.group(1)) + 2
            else:
                nl = src.find("\n", i)
                stop = n if nl < 0 else nl
            out.append(blank(src[i:stop]))
            i = stop
        elif ch == "[" and re.match(r"\[(=*)\[", src[i:i + 64]):
            eq = re.match(r"\[(=*)\[", src[i:i + 64]).group(1)
            close = src.find("]" + eq + "]", i)
            stop = n if close < 0 else close + len(eq) + 2
            out.append(blank(src[i:stop]))
            i = stop
        elif ch in "\"'":
            j = i + 1
            while j < n and src[j] != ch and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            out.append(blank(src[i:j + 1]))
            i = j + 1
        else:
            out.append(ch)
            i += 1
    return "".join(out)


def declared_locals(code: str) -> set[str]:
    """Names a file declares itself: locals, local functions, parameters, loop variables, and
    globals it defines (`function Name(`)."""
    names: set[str] = set()
    for m in re.finditer(r"\blocal\s+function\s+(\w+)", code):
        names.add(m.group(1))
    for m in re.finditer(r"\blocal\s+(?!function\b)([\w\s,]+?)(?:=|\n|;|$)", code):
        names.update(w for w in re.split(r"[\s,]+", m.group(1)) if w and w not in LUA_KEYWORDS)
    for m in re.finditer(r"\bfunction\s*[\w.:]*\s*\(([^)]*)\)", code):
        names.update(w for w in re.split(r"[\s,]+", m.group(1)) if re.match(r"^\w+$", w))
    for m in re.finditer(r"\bfor\s+([\w\s,]+?)\s*(?:=|\bin\b)", code):
        names.update(w for w in re.split(r"[\s,]+", m.group(1)) if w)
    for m in re.finditer(r"^\s*function\s+(\w+)\s*\(", code, re.M):
        names.add(m.group(1))
    return names


def _site(path: Path, code: str, pos: int, repo: Path) -> str:
    return "%s:%d" % (path.relative_to(repo).as_posix(), code.count("\n", 0, pos) + 1)


def scan_payload(repo: Path, known: set[str]) -> dict[str, dict[str, list[str]]]:
    """`{"enum": {name: [sites]}, "capi": {...}, "global": {...}}` over LibKa0s/*.lua.

    `known` is every name any source knows (both branches, both kit files): a bare call whose name
    is in none of them is the file's own upvalue or a host's, not a client assumption."""
    found: dict[str, dict[str, list[str]]] = {k: {} for k in FLAG_KINDS}

    def add(kind: str, name: str, site: str) -> None:
        sites = found[kind].setdefault(name, [])
        if site not in sites:
            sites.append(site)

    for path in sorted((repo / PAYLOAD).glob("*.lua")):
        code = strip_lua(path.read_text(encoding="utf-8", errors="replace"))
        for m in re.finditer(r"(?<![\w.:])Enum\.(\w+)(?:\.(\w+))?", code):
            add("enum", m.group(1) + ("." + m.group(2) if m.group(2) else ""), _site(path, code, m.start(), repo))
        for m in re.finditer(r"\blocal\s+(\w+)\s*(?:,\s*\w+\s*)*=\s*Enum\.(\w+)\s*(?:,|$|\n)", code):
            alias, enum = m.group(1), m.group(2)
            for a in re.finditer(r"(?<![\w.:])" + re.escape(alias) + r"\.(\w+)", code):
                add("enum", enum + "." + a.group(1), _site(path, code, a.start(), repo))
        for m in re.finditer(r"(?<![\w.:])(C_\w+)\.(\w+)", code):
            add("capi", m.group(1) + "." + m.group(2), _site(path, code, m.start(), repo))
        mine = declared_locals(code)
        for m in re.finditer(r"(?<![\w.:])([A-Za-z_]\w*)\s*\(", code):
            name = m.group(1)
            if name in LUA_KEYWORDS or name in mine or name not in known:
                continue
            add("global", name, _site(path, code, m.start(), repo))
    for kind in found:
        found[kind] = dict(sorted(found[kind].items()))
    return found


def missing_on(kind: str, name: str, names: set[str], enums: dict[str, set[str]]) -> bool:
    if kind == "enum":
        table, _, member = name.partition(".")
        if table not in enums:
            return True
        return bool(member) and member not in enums[table]
    return name not in names


