def plan_apply(doc: dict, rulings: dict) -> bool:
    missing = unruled(doc, rulings)
    if missing:
        raise SystemExit("apply refuses: %d unruled (%s). Run check." % (len(missing), ", ".join(missing[:5])))
    owed = [f["key"] for f in doc["flags"] if rulings[f["key"]]["ruling"] == "fix"]
    if owed:
        raise SystemExit("apply refuses: a payload fix is owed for %s; edit LibKa0s/ and re-derive." % ", ".join(owed))
    return any(rulings[c["key"]]["ruling"] == "accept" for c in doc["candidates"] if c["key"].startswith("regen:"))


def regenerate(doc: dict, bundle: Path, repo: Path = REPO) -> list[str]:
    """Run tools/client_globals_data.lua in a scratch copy and write its output into testkit/ and
    tests/_kit/, CRLF. Answers the paths it changed."""
    flavor, branch = doc["flavor"], doc["branch"]
    raw = read_raw(bundle)
    with tempfile.TemporaryDirectory(prefix="libseeds-") as tmp:
        work = Path(tmp)
        (work / "testkit").mkdir()
        (work / "tools").mkdir()
        shutil.copy(repo / GENERATOR, work / GENERATOR)
        shutil.copy(repo / FLAVORS["retail"]["kit"], work / FLAVORS["retail"]["kit"])
        src = work / "src"
        src.mkdir()
        for name in FILES:
            (src / name).write_text(raw[name], encoding="utf-8")
        subprocess.run(["lua", GENERATOR, branch, doc["build"], doc["buildDate"], str(src)], cwd=work, check=True,
                       capture_output=True, text=True)
        text = (work / FLAVORS[flavor]["kit"]).read_text(encoding="utf-8")
    changed = []
    kit_rel = FLAVORS[flavor]["kit"]
    for rel in (kit_rel, "tests/_kit/" + Path(kit_rel).name):
        path = repo / rel
        new = text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8")
        if not path.exists() or path.read_bytes() != new:
            path.write_bytes(new)
            changed.append(rel)
    return changed


