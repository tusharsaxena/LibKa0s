def lua_blocks(text: str) -> list[str]:
    """Every `local <Name> = {...}` table body, balanced on braces (Lua's `%b{}`)."""
    out = []
    for m in re.finditer(r"local \w+ = \{", text):
        depth, i = 0, m.end() - 1
        for j in range(i, len(text)):
            ch = text[j]
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    out.append(text[i:j + 1])
                    break
    return out


def upstream_names(global_api: str, frame_xml: str) -> set[str]:
    """The generator's name set: every quoted name in GlobalAPI.lua's tables and FrameXML.lua's
    first, kept when it has no dot or is `C_Name.Member`."""
    names: list[str] = []
    for block in lua_blocks(global_api):
        names += re.findall(r'"([\w.]+)"', block)
    blocks = lua_blocks(frame_xml)
    if blocks:
        names += re.findall(r'"([\w.]+)"', blocks[0])
    return {n for n in names if "." not in n or re.match(r"^C_\w+\.\w+$", n)}


def parse_enums(text: str) -> dict[str, set[str]]:
    """`{EnumName: {Member, ...}}` from LuaEnum.lua's `Enum = { X = { Y = n, ... }, ... }` block."""
    enums: dict[str, set[str]] = {}
    m = re.search(r"^Enum = \{\s*$", text, re.M)
    if not m:
        return enums
    current = None
    for line in text[m.end():].splitlines():
        if re.match(r"^\}", line):
            break
        head = re.match(r"^\t(\w+) = \{", line)
        if head:
            current = head.group(1)
            enums[current] = set()
            continue
        member = re.match(r"^\t\t(\w+) = ", line)
        if member and current:
            enums[current].add(member.group(1))
    return enums


def _long_string(text: str, name: str) -> str:
    m = re.search(name + r" = \[\[(.*?)\]\]", text, re.S)
    return m.group(1) if m else ""


def read_kit(path: Path) -> dict:
    """The kit file's fields: branch, sha, date, and `names` (live) or `base`/`added`/`removed`."""
    text = path.read_text(encoding="utf-8")
    field = lambda k: (re.search(k + r' = "([^"]*)"', text) or [None, None])[1]  # noqa: E731
    kit = {"branch": field("branch"), "sha": field("sha"), "date": field("date"), "base": field("base")}
    for part in ("names", "added", "removed"):
        kit[part] = set(_long_string(text, part).split())
    return kit


def kit_set(flavor: str, repo: Path = REPO) -> tuple[dict, set[str]]:
    """The kit file's record and its full name set (forever is live + added - removed)."""
    kit = read_kit(repo / FLAVORS[flavor]["kit"])
    if flavor == "retail":
        return kit, set(kit["names"])
    live = read_kit(repo / FLAVORS["retail"]["kit"])
    return kit, (set(live["names"]) | kit["added"]) - kit["removed"]


