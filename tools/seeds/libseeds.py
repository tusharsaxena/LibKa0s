def http_get(url: str, accept: str = "*/*") -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": accept})
    with urllib.request.urlopen(req, timeout=120) as resp:
        return resp.read()


def branch_head(branch: str) -> str:
    """The branch's head sha: `git ls-remote` (no API quota), the GitHub API as the fallback."""
    try:
        out = subprocess.run(["git", "ls-remote", GIT_URL, "refs/heads/" + branch], capture_output=True,
                             text=True, timeout=120, check=True).stdout.split()
        if out and SHA_RE.match(out[0]):
            return out[0]
    except (OSError, subprocess.SubprocessError):
        pass
    doc = json.loads(http_get(COMMIT_API.format(ref=branch), "application/vnd.github+json"))
    return doc["sha"]


def commit_date(sha: str) -> str:
    doc = json.loads(http_get(COMMIT_API.format(ref=sha), "application/vnd.github+json"))
    return doc["commit"]["committer"]["date"][:10]


def fetch_file(sha: str, name: str, cache_dir: Path) -> Path:
    """raw.githubusercontent.com first; `gh api` as the fallback, because that host times out from
    here often (DEPENDENCIES.md, the GitHub CLI row)."""
    path = cache_dir / sha / name
    if not path.exists() or path.stat().st_size == 0:
        path.parent.mkdir(parents=True, exist_ok=True)
        try:
            data = http_get(RAW_URL.format(sha=sha, file=name))
        except OSError:
            data = subprocess.run(["gh", "api", "-H", "Accept: application/vnd.github.raw",
                                   "repos/%s/contents/Resources/%s?ref=%s" % (SLUG, name, sha)],
                                  capture_output=True, timeout=300, check=True).stdout
        path.write_bytes(data)
    return path


