#!/usr/bin/env python3
"""tools/seeds/libseeds.py -- re-validate LibKa0s's client data against Ketho/BlizzardInterfaceResources.

WHAT THIS IS
    LibKa0s seeds no per-client id list of its own, but it carries two things that mirror a source
    it does not own, and nothing in the repo turns red when that source moves:

    * the kit's client name sets, testkit/client_globals_live.lua and
      testkit/client_globals_forever.lua, generated by tools/client_globals_data.lua from
      Ketho/BlizzardInterfaceResources' `live` and `forever` branches at a recorded commit sha.
      The missing-globals gate (tests/_kit/test_client_globals.lua) in every consumer reads them;
    * the ASSUMPTIONS the shipped payload (LibKa0s/*.lua) makes about each client: every
      `Enum.X.Y` member it reads, every `C_X.Y` it names and every bare global API it calls.

    This tool checks both against ONE pinned commit of one branch (the flavor's *build* is that
    commit's sha) and turns what it finds into CANDIDATES and FLAGS, each of which needs a ruling
    recorded as data. A ruling is keyed by what it ruled on, never by sha, so a re-run on a later
    commit shows only what is new.

    Candidates (key `<group>:<subject>`, ruled accept or reject):
        regen:<branch>        the branch head is not the sha the kit file records. Accepting it
                              lets `apply` regenerate testkit/client_globals_<branch>.lua (and its
                              tests/_kit/ copy) through tools/client_globals_data.lua: a kit
                              revision.

    Flags (key `shipped:<kind>:<subject>`, ruled keep or fix):
        enum        an `Enum.X.Y` member (or an `Enum.X` table) the payload reads that the branch's
                    LuaEnum.lua does not have
        capi        a `C_X.Y` the payload names that the branch's GlobalAPI.lua does not list
        global      a bare global the payload calls that the branch's GlobalAPI.lua / FrameXML.lua
                    do not list
    `keep` means the absence is by design (a guarded rung, a feature-detected read); cite the guard.
    `fix` means a payload edit is owed, and `apply` refuses while one is raised.

    Information, written to DIFF.md and never ruled:
        (a) the kit-globals diff: names the branch adds to, and removes from, the checked-in set;
        (c) the reach check: every name in the kit file's set still exists upstream (the names it
            does not reach are (a)'s removed list, said once more as the check's verdict).

THE STEPS
    python3 tools/seeds/libseeds.py status [--flavor retail|forever]
    python3 tools/seeds/libseeds.py freeze --flavor F --sha S --date <date> --bundle docs/seed-research/<date>-F
    python3 tools/seeds/libseeds.py derive --bundle B
    python3 tools/seeds/libseeds.py check  --bundle B
    python3 tools/seeds/libseeds.py rule   --tsv <scratch>/rulings.tsv --bundle B
    python3 tools/seeds/libseeds.py report --bundle B --date <date>
    python3 tools/seeds/libseeds.py apply  --bundle B --date <date>

    `status` compares the branch head (git ls-remote, the GitHub API as the fallback) with the sha
    the kit file records and with the newest bundle. `freeze` downloads GlobalAPI.lua, FrameXML.lua
    and LuaEnum.lua at the sha into ${XDG_CACHE_HOME:-~/.cache}/ka0s-seeds/ketho/<sha>/ (outside the
    checkout, so luacheck never reads the Lua files) and freezes them gzipped
    into the bundle's raw/, as clients-§10 asks, with SOURCES.md. (The source repository declares no
    license; the files are lists of the client's own API names and enum values, the facts the kit's
    name sets already carry.) `derive` reads raw/ alone, never the network, and writes candidates.json. The
    rulings live in tools/seeds/<flavor>_rulings.json, and `rule` is their only writer. `check`
    exits 1 while anything is unruled. `report` writes RULINGS.md and DIFF.md. `apply` refuses
    while anything is unruled or a `fix` is raised; with `regen:` accepted it runs the generator in
    a scratch copy, writes the result with CRLF into testkit/ and tests/_kit/, and a second run
    changes nothing. The date is always an argument; the tool never reads the clock. The kit
    file's own `date` field is the commit's date, a fact about the source, read at `freeze`.

    The shape follows the collection's addon seed tools (Drop Watcher's tools/seeds/seeds.py),
    copied as a pattern, never imported across repos.

Python 3.8+ and its standard library only.
"""

