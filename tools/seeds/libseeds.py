def read_raw(bundle: Path) -> dict[str, str]:
    out = {}
    for name in FILES:
        member = bundle / "raw" / (name + ".gz")
        if not member.exists():
            raise SystemExit("%s is missing raw/%s.gz: run libseeds.py freeze first." % (bundle, name))
        out[name] = gzip.decompress(member.read_bytes()).decode("utf-8")
    return out


def other_flavor(flavor: str) -> str:
    return "forever" if flavor == "retail" else "retail"


def derive_doc(bundle: Path, repo: Path = REPO) -> dict:
    sources = load_json(bundle / "sources.json")
    flavor, sha = sources["flavor"], sources["sha"]
    raw = read_raw(bundle)
    upstream = upstream_names(raw["GlobalAPI.lua"], raw["FrameXML.lua"])
    enums = parse_enums(raw["LuaEnum.lua"])
    if len(upstream) < 1000 or "C_Timer.After" not in upstream or "Enum" not in raw["LuaEnum.lua"][:16]:
        raise SystemExit("coverage gate: the sources at %s read as %d names; the reader is wrong, not the data." % (sha, len(upstream)))
    kit, kit_names = kit_set(flavor, repo)
    _, other_names = kit_set(other_flavor(flavor), repo)
    known = upstream | kit_names | other_names
    assumptions = scan_payload(repo, known)
    added, removed = sorted(upstream - kit_names), sorted(kit_names - upstream)
    candidates, flags = [], []
    branch = FLAVORS[flavor]["branch"]
    if kit["sha"] != sha:
        candidates.append({"key": "regen:" + branch, "name": "regenerate %s at %s" % (FLAVORS[flavor]["kit"], sha[:12]),
                           "notes": ["kit at %s (%s)" % (kit["sha"][:12], kit["date"]), "%d added, %d removed" % (len(added), len(removed))]})
    for kind in FLAG_KINDS:
        for name, sites in assumptions[kind].items():
            if missing_on(kind, name, upstream, enums):
                flags.append({"key": "shipped:%s:%s" % (kind, name), "shipped": name, "build": "absent on " + branch,
                              "notes": sites[:6] + (["+%d more" % (len(sites) - 6)] if len(sites) > 6 else [])})
    return {
        "flavor": flavor, "branch": branch, "build": sha, "buildDate": sources["shaDate"], "date": sources["date"],
        "tool": "tools/seeds/libseeds.py derive", "kit": {"path": FLAVORS[flavor]["kit"], "sha": kit["sha"], "date": kit["date"],
                                                         "names": len(kit_names)},
        "upstream": {"names": len(upstream), "enums": len(enums)},
        "diff": {"added": added, "removed": removed},
        "reach": {"kitNames": len(kit_names), "unreached": removed},
        "assumptions": {k: {"count": len(v), "missing": sum(1 for n in v if missing_on(k, n, upstream, enums))}
                        for k, v in assumptions.items()},
        "candidates": candidates, "flags": flags,
    }


def load_json(path: Path):
    if not path.exists():
        raise SystemExit("%s does not exist." % path)
    return json.loads(path.read_text(encoding="utf-8"))


def rulings_path(flavor: str, tool_dir: Path = HERE) -> Path:
    return tool_dir / ("%s_rulings.json" % flavor)


def load_rulings(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def save_rulings(path: Path, rulings: dict) -> None:
    write_json(path, rulings)


def load_doc(bundle: Path) -> dict:
    path = bundle / "candidates.json"
    if not path.exists():
        raise SystemExit("%s has no candidates.json: run libseeds.py derive first." % bundle)
    return load_json(path)


def all_keys(doc: dict) -> list[str]:
    return [c["key"] for c in doc["candidates"]] + [f["key"] for f in doc["flags"]]


def unruled(doc: dict, rulings: dict) -> list[str]:
    return [k for k in all_keys(doc) if k not in rulings]


def set_ruling(rulings: dict, key: str, ruling: str, reason: str) -> None:
    m = KEY_RE.match(key or "")
    if not m or (m.group("kind") and m.group("kind") not in FLAG_KINDS):
        raise SystemExit("%r is not regen:<branch> or shipped:<enum|capi|global>:<name>." % key)
    allowed = FLAG_RULINGS if m.group("kind") else CANDIDATE_RULINGS
    if ruling not in allowed:
        raise SystemExit("the ruling for %s must be %s; got %r." % (key, " or ".join(allowed), ruling))
    reason = (reason or "").strip()
    if not reason or "\n" in reason:
        raise SystemExit("the reason for %s must be one non-empty line." % key)
    rulings[key] = {"ruling": ruling, "reason": reason}


def read_tsv(path: Path) -> list[tuple[str, str, str]]:
    out = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            raise SystemExit("%s: a ruling line is key<TAB>ruling<TAB>reason; got %r" % (path, line))
        out.append(tuple(p.strip() for p in parts))
    return out


def bundles(flavor: str, root: Path = RESEARCH) -> list[Path]:
    return sorted(p for p in root.glob("*-" + flavor) if (p / "candidates.json").exists())


def status_line(head: str, kit_sha: str, found: list[Path]) -> str:
    """`CURRENT <sha> (...)`, else `NEW <sha> (...)`; the first word is what
    /dev-copilot:validate-seeds reads. Current means the newest bundle ruled this head."""
    if found:
        last = found[-1]
        if load_doc(last)["build"] == head:
            return "CURRENT %s (%s; kit at %s)" % (head, last.name, kit_sha)
        return "NEW %s (last ruled %s, %s; kit at %s)" % (head, load_doc(last)["build"], last.name, kit_sha)
    return "NEW %s (no bundle yet; kit at %s)" % (head, kit_sha)


