def write_repo_text(path: Path, text: str, crlf: bool = True) -> None:
    """Every authored text file in this repo is CRLF on disk (.gitattributes); .py is LF."""
    path.parent.mkdir(parents=True, exist_ok=True)
    body = text.replace("\r\n", "\n")
    if crlf:
        body = body.replace("\n", "\r\n")
    path.write_bytes(body.encode("utf-8"))


def write_json(path: Path, doc) -> None:
    write_repo_text(path, json.dumps(doc, indent=2, sort_keys=True, ensure_ascii=False) + "\n")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


